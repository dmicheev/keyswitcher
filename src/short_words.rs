//! Хардкод-правила переключения для коротких слов (1–2 символа).
//!
//! Частотные словари и n-граммы на словах из 1–2 букв не работают:
//! у предлогов и местоимений («в», «не», «на»…) частоты сопоставимы с
//! латинским «мусором», а n-граммной модели не на что опереться. Поэтому
//! такие слова решаются замкнутой картой: русский ключ есть — слово
//! русское (переключаемся на RU и ретро-фиксом меняем латинский ввод на
//! русский вид), ключа нет — считаем слово латиницей и не трогаем.
//! Приоритет — у русского языка: коллизии вроде «vs»/«мы» разрешаются
//! в пользу «мы».
//!
//! Список — служебные слова: предлоги, союзы, частицы, местоимения,
//! междометия. Намеренно отброшены комбинации, правдоподобные как
//! латиница: «ой»/«ай»/«эй» (jq/fq/wq — конфликт с утилитой jq),
//! «ем» (tv), «ту» (to-подобные последовательности) и т.п.

/// Максимальная длина слова, решаемого хардкод-правилами.
pub const MAX_LEN: usize = 2;

/// Русские слова длиной 1–2 символа. Отсортированы по байтам —
/// требование бинарного поиска в [`is_short_ru`] (группировка по длине
/// нарушила бы порядок: у «с»/«т»… кодовые точки начинаются с `D1`, а не `D0`).
#[rustfmt::skip]
const SHORT_RU: &[&str] = &[
    "а", "бы", "в", "во", "вы", "да", "до", "ее", "ей", "её",
    "же", "за", "и", "из", "им", "их", "к", "ли", "мы", "на", "не",
    "ни", "но", "ну", "о", "об", "он", "от", "по", "с", "со",
    "те", "то", "ты", "у", "уж", "фу", "ха", "эх", "я",
];

/// Короткое слово — русское? Аргумент — нижний регистр слова в RU-виде.
pub fn is_short_ru(word_lower: &str) -> bool {
    SHORT_RU.binary_search(&word_lower).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::engine::Layout;
    use crate::keymap::{keycode_for, KeyChars, StaticKeymap};

    #[test]
    fn list_is_sorted_for_binary_search() {
        assert!(SHORT_RU.windows(2).all(|w| w[0] < w[1]));
    }

    #[test]
    fn list_holds_short_letter_words() {
        for w in SHORT_RU {
            assert!(w.chars().count() <= MAX_LEN, "{w}");
            assert!(w.chars().all(char::is_alphabetic), "{w}");
        }
    }

    #[test]
    fn membership() {
        for w in [
            "в", "я", "не", "на", "из", "об", "же", "бы", "ее", "её", "их",
        ] {
            assert!(is_short_ru(w), "{w}");
        }
        // Латинские виды типичных английских слов (to/in/he/no...) и мусор.
        for w in [
            "ф", "d", "ещ", "шт", "ру", "тщ", "вщ", "вв", "нет", "ой", "ем",
        ] {
            assert!(!is_short_ru(w), "{w}");
        }
    }

    #[test]
    fn every_word_typeable_in_both_layouts() {
        for w in SHORT_RU {
            for c in w.chars() {
                let code =
                    keycode_for(Layout::Ru, c).unwrap_or_else(|| panic!("нет клавиши для '{c}'"));
                assert!(
                    StaticKeymap.chars_for(code, false).is_some(),
                    "клавиша {code:#x} для '{c}' ({w})"
                );
            }
        }
    }
}
